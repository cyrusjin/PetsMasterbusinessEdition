const { STORAGE_KEYS } = require('../../utils/constants');
const MAX_CHAT_MESSAGES = 120;

function normalizeStoredMessages(list) {
  if (!Array.isArray(list)) return [];
  return list
    .filter((m) => m && m.id && m.content && (m.role === 'user' || m.role === 'ai') && !m.pending)
    .map((m) => ({
      id: String(m.id),
      role: m.role,
      content: String(m.content),
      time: m.time || '',
      source: m.source || (m.role === 'ai' ? 'local' : '')
    }))
    .slice(-MAX_CHAT_MESSAGES);
}

function loadChatHistory() {
  try {
    const raw = wx.getStorageSync(STORAGE_KEYS.AI_CONSULT);
    if (!raw || typeof raw !== 'object') {
      return { messages: [], conversationId: '' };
    }
    return {
      messages: normalizeStoredMessages(raw.messages),
      conversationId: raw.conversationId ? String(raw.conversationId) : ''
    };
  } catch (e) {
    return { messages: [], conversationId: '' };
  }
}

function saveChatHistory(messages, conversationId) {
  try {
    wx.setStorageSync(STORAGE_KEYS.AI_CONSULT, {
      messages: normalizeStoredMessages(messages),
      conversationId: conversationId ? String(conversationId) : '',
      updatedAt: Date.now()
    });
  } catch (e) {
    // 存储满或异常时忽略，不影响问答
  }
}

function clearChatHistory() {
  try {
    wx.removeStorageSync(STORAGE_KEYS.AI_CONSULT);
  } catch (e) {
    // ignore
  }
}

