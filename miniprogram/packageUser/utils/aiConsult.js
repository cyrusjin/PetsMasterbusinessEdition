function buildFallbackReply(userText) {
  const hint = String(userText || '').trim().slice(0, 40);
  if (!hint) return EMPTY_REPLY;
  return (
    `关于「${hint}」：我没找到完全对应的条目，但不代表没事。\n\n` +
    '宠物很多不适（感染、异物、胰腺炎、泌尿问题、中毒等）外表看起来差不多，单靠文字容易误判。\n\n' +
    '建议你：\n' +
    '1. 先观察精神、食欲、大小便、呼吸是否异常\n' +
    '2. 暂勿自行用药（尤其人用止痛/退烧药）\n' +
    '3. 心里没底或症状还在——直接去医院做全面检查最靠谱\n\n' +
    '你也可以把症状再说具体一点（例如有没有吐、拉、发烧、精神差），我再按常见护理给你参考。' +
    HOSPITAL_FOOTER
  );
}

function hasUrgentSignal(text) {
  return URGENT_KEYS.some((k) => text.indexOf(k) >= 0);
}

const LIGHT_DISCLAIMER = '\n\n⚠️ 仅供日常参考。若加重、反复或你心里没底，请就医做全面检查。';

function matchLocal(msg) {
  const text = String(msg || '').trim().toLowerCase();
  if (!text) {
    return { reply: EMPTY_REPLY, source: 'local' };
  }

  if (hasUrgentSignal(text)) {
    return { reply: URGENT_REPLY, source: 'local' };
  }

  let best = null;
  let bestScore = 0;
  KB.forEach((item) => {
    let score = 0;
    item.keys.forEach((k) => {
      const key = String(k || '').toLowerCase();
      if (!key) return;
      if (text.indexOf(key) >= 0) {
        score += Math.max(key.length, 2);
      }
    });
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  });

  if (best && bestScore > 0) {
    const body = String(best.reply || '').trim();
    return {
      reply: ensureReply(body ? `${body}${LIGHT_DISCLAIMER}` : '', text),
      source: 'local'
    };
  }

  return { reply: buildFallbackReply(text), source: 'local' };
}

/** 保证永远有可用文案（兜底到医院建议） */
function ensureReply(reply, userMsg) {
  const text = String(reply || '').trim();
  if (text) return text;
  return buildFallbackReply(userMsg) || EMPTY_REPLY || SAFE_LAST_RESORT;
}

const SAFE_LAST_RESORT =
  '为了毛孩子安全，建议尽快去宠物医院做一次全面检查。线上问答无法替代面诊。';

function buildPetContext(pet) {
  if (!pet) return null;
  return {
    name: pet.name || '',
    type: pet.type || '',
    breed: pet.breed || '',
    gender: pet.gender || '',
    age: pet.age || '',
    weight: pet.weight || ''
  };
}

function askPetAi(opts = {}) {
  const msg = String(opts.msg || '').trim().slice(0, 200);
  const conversationId = opts.conversationId || '';
  const local = matchLocal(msg);
  return Promise.resolve({
    reply: ensureReply(local.reply, msg),
    conversationId,
    source: 'local'
  });
}

